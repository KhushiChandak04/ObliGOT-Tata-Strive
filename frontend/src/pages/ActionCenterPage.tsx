import {useEffect,useState,type FormEvent} from "react";
import {Link,useSearchParams} from "react-router-dom";
import Dialog from "../components/ui/Dialog";
import FormField from "../components/ui/FormField";
import PageHeader from "../components/ui/PageHeader";
import StateMessage from "../components/ui/StateMessage";
import StatusBadge from "../components/ui/StatusBadge";
import AlertDetail from "../features/alerts/AlertDetail";
import AlertList from "../features/alerts/AlertList";
import {api} from "../services/functions.service";
import {useResource} from "../lib/useResource";
import {CATEGORY_LABELS,TODAY_COUNT,todaysAlerts} from "../lib/alerts";
import {formatDate} from "../lib/utils";
import type {ActionItem,Alert,AlertCategory,Priority} from "../types";

export default function ActionCenterPage(){
 const {data,error,loading,reload}=useResource(async()=>{
  // One request returns active and reviewed alerts; the split happens below so every list agrees.
  const [alerts,partners,actions]=await Promise.all([api.alerts.list({includeReviewed:true}),api.partners.list(),api.actions.list()]);
  return {alerts,partners,actions};
 },[]);
 const [params,setParams]=useSearchParams();
 const [level,setLevel]=useState<Priority|"all">("all");
 const [category,setCategory]=useState<AlertCategory|"all">("all");
 const [partnerFilter,setPartnerFilter]=useState("all");
 const [showReviewed,setShowReviewed]=useState(false);
 const [showDoneTasks,setShowDoneTasks]=useState(false);
 const [reassigning,setReassigning]=useState<ActionItem|null>(null);
 const [notice,setNotice]=useState("");
 const [taskError,setTaskError]=useState("");

 const partnerName=new Map((data?.partners??[]).map(p=>[p.id,p.name]));
 const nameOf=(id:string)=>partnerName.get(id);
 const all=data?.alerts.alerts??[];
 const active=all.filter(a=>!a.hidden_by_review);
 const today=todaysAlerts(all);
 const listed=(showReviewed?all:active).filter(a=>(level==="all"||a.priority.level===level)&&(category==="all"||a.category===category)&&(partnerFilter==="all"||a.partner_id===partnerFilter));
 const openId=params.get("alert");
 const openAlert=openId?all.find(a=>a.id===openId)??null:null;
 const highlightedTask=params.get("task");
 const tasks=(data?.actions??[]).filter(t=>showDoneTasks||t.status==="open"||t.status==="in_review")
  .sort((a,b)=>({high:0,medium:1,low:2}[a.priority]-{high:0,medium:1,low:2}[b.priority])||(a.due_date??"9999").localeCompare(b.due_date??"9999"));
 const filtersActive=level!=="all"||category!=="all"||partnerFilter!=="all"||showReviewed;

 useEffect(()=>{
  if(highlightedTask&&data)document.getElementById(`task-${highlightedTask}`)?.scrollIntoView({block:"center"});
 },[highlightedTask,data]);

 const open=(alert:Alert)=>setParams(current=>{const next=new URLSearchParams(current);next.set("alert",alert.id);return next;});
 const close=()=>setParams(current=>{const next=new URLSearchParams(current);next.delete("alert");return next;});
 const changed=(message:string)=>{close();setNotice(message);reload();};

 async function markDone(task:ActionItem){
  setTaskError("");
  try{await api.actions.update(task.id,{status:"done"});setNotice(`Marked “${task.title}” done. Fix the underlying record to clear its alert.`);reload();}
  catch(e){setTaskError(e instanceof Error?e.message:"Could not update the task.");}
 }

 return <>
  <PageHeader eyebrow="PARTNERSHIP OPERATIONS" title="Action center" description={data?`Alerts are generated by deterministic rules from stored records as of ${formatDate(data.alerts.as_of)} (IST). Review each alert's evidence before acting.`:"Prioritised, evidence-backed alerts and follow-up tasks."}/>
  {error&&<StateMessage kind="error" title="Could not load the action center" detail={error.message} action={<button className="button button-secondary" onClick={reload}>Retry</button>}/>}
  {notice&&<p className="success-message page-message" role="status">{notice}</p>}
  {openId&&data&&!openAlert&&<p className="form-error page-message" role="alert">That alert is no longer raised — its record may have been resolved or changed.</p>}
  {loading&&!data?<StateMessage kind="loading" title="Evaluating rules…"/>:data&&<>
   <div className="summary-strip" aria-label="Alert summary">
    <div><span>Open alerts</span><strong>{active.length}</strong></div>
    <div><span>High</span><strong className="tone-high">{active.filter(a=>a.priority.level==="high").length}</strong></div>
    <div><span>Medium</span><strong className="tone-medium">{active.filter(a=>a.priority.level==="medium").length}</strong></div>
    <div><span>Low</span><strong>{active.filter(a=>a.priority.level==="low").length}</strong></div>
    <div><span>Deferred or dismissed</span><strong>{data.alerts.counts.hidden_by_review}</strong></div>
    <div><span>Open tasks</span><strong>{(data.actions??[]).filter(t=>t.status==="open"||t.status==="in_review").length}</strong></div>
   </div>

   <section className="panel" aria-labelledby="today-heading">
    <div className="panel-heading"><div><h2 id="today-heading">Today's {TODAY_COUNT}</h2><p>Highest-priority open alerts without a task yet. A shortcut, not a limit — every alert is listed below.</p></div></div>
    {today.length?<AlertList alerts={today} partnerName={nameOf} onOpen={open} ranked/>:<StateMessage title="Nothing needs attention right now" detail="Every open alert already has a task, or there are no open alerts."/>}
   </section>

   <section className="panel section-gap" aria-labelledby="all-heading">
    <div className="panel-heading"><div><h2 id="all-heading">All alerts</h2><p>Sorted by priority score. {data.alerts.note}</p></div></div>
    <div className="toolbar">
     <label className="toolbar-select"><span>Priority</span><select value={level} onChange={e=>setLevel(e.target.value as Priority|"all")}><option value="all">All</option><option value="high">High</option><option value="medium">Medium</option><option value="low">Low</option></select></label>
     <label className="toolbar-select"><span>Category</span><select value={category} onChange={e=>setCategory(e.target.value as AlertCategory|"all")}><option value="all">All</option>{(Object.keys(CATEGORY_LABELS) as AlertCategory[]).map(c=><option key={c} value={c}>{CATEGORY_LABELS[c]}</option>)}</select></label>
     <label className="toolbar-select"><span>Partner</span><select value={partnerFilter} onChange={e=>setPartnerFilter(e.target.value)}><option value="all">All</option>{data.partners.map(p=><option key={p.id} value={p.id}>{p.name}</option>)}</select></label>
     <label className="toolbar-check"><input type="checkbox" checked={showReviewed} onChange={e=>setShowReviewed(e.target.checked)}/> Include deferred and dismissed</label>
     <span className="muted" aria-live="polite">{listed.length} alerts</span>
     {filtersActive&&<button className="text-button" onClick={()=>{setLevel("all");setCategory("all");setPartnerFilter("all");setShowReviewed(false);}}>Clear filters</button>}
    </div>
    {listed.length?<AlertList alerts={listed} partnerName={nameOf} onOpen={open}/>:<StateMessage title={all.length?"No alerts match these filters":"No alerts"} detail={all.length?"Change or clear the filters.":"No record currently triggers a rule."}/>}
   </section>

   <section className="panel section-gap" aria-labelledby="tasks-heading">
    <div className="panel-heading"><div><h2 id="tasks-heading">Tasks</h2><p>Assigned follow-ups. Completing a task does not clear an alert — updating the underlying record does.</p></div>
     <label className="toolbar-check"><input type="checkbox" checked={showDoneTasks} onChange={e=>setShowDoneTasks(e.target.checked)}/> Show done and deferred</label></div>
    {taskError&&<p className="form-error page-message" role="alert">{taskError}</p>}
    {tasks.length?<div className="table-panel inner-table"><table>
     <thead><tr><th scope="col">Task</th><th scope="col">Priority</th><th scope="col">Status</th><th scope="col">Due</th><th scope="col">Owner</th><th scope="col"><span className="visually-hidden">Actions</span></th></tr></thead>
     <tbody>{tasks.map(t=><tr key={t.id} id={`task-${t.id}`} className={highlightedTask===t.id?"row-highlight":undefined}>
      <td><strong>{t.title}</strong><small>{t.related_partner_id?<Link className="text-link" to={`/partners/${t.related_partner_id}`}>{nameOf(t.related_partner_id)??t.related_partner_id}</Link>:"No partner"}
       {t.source_alert_id&&<> · {all.some(a=>a.id===t.source_alert_id)?<button className="text-button inline" onClick={()=>setParams(current=>{const next=new URLSearchParams(current);next.set("alert",t.source_alert_id!);return next;})}>From alert</button>:"From a resolved alert"}</>}
       {t.source_label==="demo"?" · demo":""}</small></td>
      <td><StatusBadge value={t.priority}/></td><td><StatusBadge value={t.status}/></td><td>{formatDate(t.due_date)}</td><td>{t.owner??"Unassigned"}</td>
      <td className="row-actions">{(t.status==="open"||t.status==="in_review")&&<><button className="button button-secondary button-small" onClick={()=>void markDone(t)} aria-label={`Mark ${t.title} done`}>Mark done</button><button className="text-button" onClick={()=>setReassigning(t)} aria-label={`Reassign ${t.title}`}>Reassign</button></>}</td>
     </tr>)}</tbody>
    </table></div>:<StateMessage title="No open tasks" detail="Create a task from an alert to assign a follow-up."/>}
   </section>
  </>}

  <Dialog open={Boolean(openAlert)} title="Alert details" onClose={close} wide>
   {openAlert&&data&&<AlertDetail key={openAlert.id} alert={openAlert} asOf={data.alerts.as_of} partnerName={nameOf}
     related={all.filter(a=>openAlert.related_alert_ids.includes(a.id))} onChanged={changed} onOpenRelated={open}/>}
  </Dialog>
  <Dialog open={reassigning!==null} title="Reassign task" onClose={()=>setReassigning(null)}>
   {reassigning&&<ReassignForm task={reassigning} onCancel={()=>setReassigning(null)} onSaved={owner=>{setReassigning(null);setNotice(`Reassigned “${reassigning.title}” to ${owner}.`);reload();}}/>}
  </Dialog>
 </>;
}

function ReassignForm({task,onSaved,onCancel}:{task:ActionItem;onSaved:(owner:string)=>void;onCancel:()=>void}){
 const [owner,setOwner]=useState(task.owner&&task.owner!=="Unassigned"?task.owner:"");
 const [error,setError]=useState("");
 const [busy,setBusy]=useState(false);
 async function submit(e:FormEvent){
  e.preventDefault();
  if(owner.trim().length<2){setError("Enter the new owner (at least 2 characters).");return;}
  setBusy(true);
  try{await api.actions.update(task.id,{owner:owner.trim()});onSaved(owner.trim());}
  catch(err){setError(err instanceof Error?err.message:"Could not reassign the task.");}
  finally{setBusy(false);}
 }
 return <form className="form-grid" onSubmit={e=>void submit(e)} noValidate>
  <p className="form-wide muted">{task.title} · currently {task.owner??"Unassigned"}</p>
  <div className="form-wide"><FormField id="reassign-owner" label="New owner *" error={error}><input value={owner} maxLength={120} onChange={e=>{setOwner(e.target.value);setError("");}} autoFocus/></FormField></div>
  <div className="form-wide form-actions"><button type="button" className="button button-secondary" onClick={onCancel} disabled={busy}>Cancel</button><button className="button button-primary" disabled={busy}>{busy?"Saving…":"Reassign"}</button></div>
 </form>;
}
